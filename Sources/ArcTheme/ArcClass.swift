/// its `bodyBase64` to get the served sheet, take every match of
/// `\.([A-Za-z_][A-Za-z0-9_-]*)` whose preceding byte is neither a digit nor a
/// dot (the rule `HTMLClassValidator.parseClasses` applies, so `1.5rem` is not
